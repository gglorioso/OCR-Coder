"""
Phase 3.4 -- Stage 2 (Reasoning Fine-Tune) Training

Multi-GPU training with 4x H100s. Native bfloat16, no bitsandbytes.
Initializes from Stage 1 checkpoint and fine-tunes on reasoning Q&A data
generated by GPT-4o-mini.

DDP is used for parameter broadcasting at init, but gradient sync is
handled manually (all-reduce on trainable grads only) via no_sync() to
prevent NCCL deadlocks when individual ranks hit NaN/OOM.

Key differences from Stage 1:
  - Loads Stage 1 projector + LoRA weights before training
  - Dataset: JSONL with sequence_tensors (multi-chunk) + qa_pairs
  - Each record can produce multiple training examples (one per Q&A pair)
  - Lower learning rates (half of Stage 1) to preserve Stage 1 knowledge
  - Multi-chunk vision: concatenate features from all chunks, project each,
    then concatenate projected tokens

Architecture unchanged:
  Code image -> SigLIP features [1024, 1152]
             -> ConvRoPEProjector [256, 2048]
             -> splice into token embeddings at placeholder positions
             -> DeepSeek-Coder-V2-Lite-Instruct (bfloat16 + LoRA)
             -> cross-entropy loss on answer tokens only
"""

