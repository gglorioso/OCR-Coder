# Model loading with Stage 1 checkpoint
# ---------------------------------------------------------------------------
def load_model(model_path: str, stage1_ckpt_dir: str, device: torch.device):
    """Load tokenizer, bfloat16 LLM with LoRA, ConvRoPEProjector,
    then restore Stage 1 weights (projector + LoRA adapter)."""

    if is_main_process():
        print(f"[load_model] Loading tokenizer from {model_path}")
    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    if is_main_process():
        print(f"[load_model] Loading LLM in bfloat16 from {model_path}")
    llm = AutoModelForCausalLM.from_pretrained(
        model_path,
        device_map={"": device},
        trust_remote_code=True,
        torch_dtype=torch.bfloat16,
    )

    # ---- Load Stage 1 LoRA adapter ----
    stage1_dir = Path(stage1_ckpt_dir)
    lora_adapter_dir = stage1_dir / "lora_adapter"

    if lora_adapter_dir.exists():
        if is_main_process():
            print(f"[load_model] Loading Stage 1 LoRA adapter from {lora_adapter_dir}")
        llm = PeftModel.from_pretrained(
            llm,
            str(lora_adapter_dir),
            is_trainable=True,
        )
        if is_main_process():
            print("[load_model] Stage 1 LoRA adapter loaded successfully")
    else:
        if is_main_process():
            print(f"[load_model] WARNING: No Stage 1 LoRA adapter at {lora_adapter_dir}")
            print("[load_model] Applying fresh LoRA config (Stage 1 LoRA weights missing!)")
        lora_config = LoraConfig(
            r=LORA_R,
            lora_alpha=LORA_ALPHA,
            lora_dropout=LORA_DROPOUT,
            target_modules=[
                "q_proj", "kv_a_proj_with_mqa", "kv_b_proj", "o_proj",
                "gate_proj", "up_proj", "down_proj",
            ],
            bias="none",
            task_type="CAUSAL_LM",
        )
        llm = get_peft_model(llm, lora_config)

    if is_main_process():
        llm.print_trainable_parameters()

    # ---- Projector ----
    projector = ConvRoPEProjector(feat_dim=1152, proj_dim=2048)

    projector_ckpt_path = stage1_dir / "projector.pth"
    if projector_ckpt_path.exists():
        if is_main_process():
            print(f"[load_model] Loading Stage 1 projector from {projector_ckpt_path}")
        ckpt = torch.load(str(projector_ckpt_path), map_location="cpu", weights_only=True)
        if "projector_state_dict" in ckpt:
            projector.load_state_dict(ckpt["projector_state_dict"])
        else:
            projector.load_state_dict(ckpt)
        if is_main_process():
            print("[load_model] Projector weights loaded successfully")
    else:
        if is_main_process():
            print(f"[load_model] WARNING: No projector checkpoint at {projector_ckpt_path}")
            print("[load_model] Using random init (Stage 1 projector weights missing!)")

    projector.to(device=device, dtype=torch.bfloat16)

    model = CoderVLModel(projector, llm)

    # Print param counts
    if is_main_process():
        proj_trainable = sum(p.numel() for p in model.projector.parameters() if p.requires_grad)
        lora_trainable = sum(p.numel() for p in model.llm.parameters() if p.requires_grad)
        frozen = sum(p.numel() for p in model.llm.parameters() if not p.requires_grad)
        print(f"[load_model] Projector trainable params: {proj_trainable:,}")
        print(f"[load_model] LoRA trainable params:      {lora_trainable:,}")
        print(f"[load_model] Frozen LLM params:          {frozen:,}")

    return model, tokenizer


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------
def validate(model: nn.Module, val_loader: DataLoader, device: torch.device) -> float:
    """Run validation on all ranks (NCCL timeout safety), return average loss."""
    model.eval()
    total_loss = 0.0
    n_batches = 0

    with torch.no_grad():
        for batch in val_loader:
            if batch is None:
                continue
            vision = batch["vision"].to(device)
            input_ids = batch["input_ids"].to(device)
            attention_mask = batch["attention_mask"].to(device)
            labels = batch["labels"].to(device)
            n_visual_tokens = batch["n_visual_tokens"]

            try:
                with torch.cuda.amp.autocast(dtype=torch.bfloat16):
                    loss = model(vision, input_ids, attention_mask, labels, n_visual_tokens)
                if not torch.isfinite(loss):
                    continue
                total_loss += loss.item()
                n_batches += 1
            except RuntimeError as e:
                if "out of memory" in str(e):
                    torch.cuda.empty_cache()
                    continue
                raise

    model.train()
    return total_loss / n_batches if n_batches > 0 else float("inf")


