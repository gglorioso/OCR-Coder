class ReasoningDataset(Dataset):
    """Loads reasoning Q&A data from a JSONL file.

    Each JSONL record has:
      - sequence_tensors: list of paths to precomputed SigLIP [1024, 1152] .pt files
      - qa_pairs: list of {question, answer} dicts

    One record produces len(qa_pairs) training examples. We flatten all
    (record, qa_pair_index) tuples at init time for efficient indexing.
    """

    def __init__(
        self,
        jsonl_path: str,
        tokenizer,
        repo_root: str,
        max_text_tokens: int = MAX_TEXT_TOKENS,
        max_chunks: int = MAX_CHUNKS,
    ) -> None:
        self.tokenizer = tokenizer
        self.max_text_tokens = max_text_tokens
        self.max_chunks = max_chunks
        self.repo_root = Path(repo_root)

        # Load JSONL and flatten to (record, qa_index) pairs
        self.records: List[Dict] = []
        self.flat_samples: List[tuple] = []  # (record_idx, qa_idx)

        jsonl_path = Path(jsonl_path)
        if not jsonl_path.exists():
            raise FileNotFoundError(f"Reasoning dataset not found: {jsonl_path}")

        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line_num, line in enumerate(f):
                line = line.strip()
                if not line:
                    continue
                try:
                    record = json.loads(line)
                except json.JSONDecodeError as e:
                    print(f"[ReasoningDataset] Skipping malformed line {line_num}: {e}")
                    continue

                # Validate required fields
                if "sequence_tensors" not in record or "qa_pairs" not in record:
                    print(f"[ReasoningDataset] Skipping line {line_num}: missing fields")
                    continue
                if not record["qa_pairs"]:
                    continue

                # Cap chunks
                tensors = record["sequence_tensors"][:self.max_chunks]
                record["sequence_tensors"] = tensors

                rec_idx = len(self.records)
                self.records.append(record)

                for qa_idx in range(len(record["qa_pairs"])):
                    self.flat_samples.append((rec_idx, qa_idx))

        print(f"[ReasoningDataset] Loaded {len(self.records)} records, "
              f"{len(self.flat_samples)} Q&A samples from {jsonl_path}")

    def __len__(self) -> int:
        return len(self.flat_samples)

    def __getitem__(self, idx: int) -> Optional[dict]:
        rec_idx, qa_idx = self.flat_samples[idx]
        record = self.records[rec_idx]

        try:
            # Load and concatenate vision tensors
            tensor_paths = record["sequence_tensors"]
            n_chunks = len(tensor_paths)

            vision_chunks = []
            for tp in tensor_paths:
                full_path = self.repo_root / tp
                if not full_path.exists():
                    print(f"[ReasoningDataset] Missing tensor: {full_path}")
                    return None
                chunk = torch.load(str(full_path), map_location="cpu", weights_only=True)
                # Cast to float32 for safety (will be cast to bfloat16 later)
                chunk = chunk.float()
                if chunk.shape != (1024, 1152):
                    print(f"[ReasoningDataset] Bad shape {chunk.shape} in {full_path}")
                    return None
                vision_chunks.append(chunk)

            # Concatenate: [n_chunks * 1024, 1152]
            vision = torch.cat(vision_chunks, dim=0)

            # Get Q&A
            qa = record["qa_pairs"][qa_idx]
            question = qa["question"]
            answer = qa["answer"]

            # Tokenize
            pad_id = self.tokenizer.pad_token_id
            eos_id = self.tokenizer.eos_token_id

            n_visual_tokens = n_chunks * N_VISUAL_TOKENS

            # Format: [visual_placeholders] \nQuestion: {question}\nAnswer: {answer}<eos>
            prompt_text = f"\nQuestion: {question}\nAnswer: "
            prompt_ids = self.tokenizer.encode(prompt_text, add_special_tokens=False)

            answer_ids = self.tokenizer.encode(answer, add_special_tokens=False)

            # Truncate answer if needed (leave room for prompt + eos)
            max_answer_len = self.max_text_tokens - len(prompt_ids) - 1  # -1 for eos
            if max_answer_len <= 0:
                # Prompt alone exceeds budget -- truncate prompt
                prompt_ids = prompt_ids[:self.max_text_tokens // 2]
                max_answer_len = self.max_text_tokens - len(prompt_ids) - 1

            if len(answer_ids) > max_answer_len:
                answer_ids = answer_ids[:max_answer_len]

            placeholder = [pad_id] * n_visual_tokens
            input_ids = placeholder + prompt_ids + answer_ids + [eos_id]

            # Labels: only supervise on the answer tokens + eos
            labels = (
                [-100] * n_visual_tokens
                + [-100] * len(prompt_ids)
                + answer_ids
                + [eos_id]
            )

            assert len(input_ids) == len(labels), \
                f"Length mismatch: input_ids={len(input_ids)}, labels={len(labels)}"

            return {
                "vision": vision,
                "input_ids": torch.tensor(input_ids, dtype=torch.long),
                "labels": torch.tensor(labels, dtype=torch.long),
                "n_chunks": n_chunks,
            }

        except Exception as e:
            print(f"[ReasoningDataset] Error loading record {rec_idx}, qa {qa_idx}: {e}")
            traceback.print_exc()
            return None


# ---------------------------------------------------------------------------
# collate_fn
# ---------------------------------------------------------------------------
def collate_fn(batch: list) -> Optional[dict]:
    """Collate with None filtering, right-padding, and multi-chunk vision padding.

    All samples in a batch must have the same number of vision chunks (we pad
    to the max n_chunks in the batch by repeating the last chunk's features).
    """
    batch = [b for b in batch if b is not None]
    if not batch:
        return None

    pad_id = collate_fn.pad_token_id

    # Find max chunks and max text length in this batch
    max_chunks = max(b["n_chunks"] for b in batch)
    max_visual_tokens = max_chunks * N_VISUAL_TOKENS
    max_text_len = max(b["input_ids"].size(0) for b in batch)

    # We need to re-pad input_ids and labels so visual placeholder region
    # matches max_visual_tokens for all samples
    vision_list = []
    input_ids_list = []
    labels_list = []
    attention_mask_list = []

    for b in batch:
        n_chunks = b["n_chunks"]
        n_visual = n_chunks * N_VISUAL_TOKENS
        extra_visual = max_visual_tokens - n_visual

        # Pad vision to max_chunks * 1024 tokens
        vis = b["vision"]  # [n_chunks * 1024, 1152]
        if n_chunks < max_chunks:
            # Pad with zeros (projector output for zero input will be near-zero)
            pad_vis = torch.zeros(
                (max_chunks - n_chunks) * 1024, 1152, dtype=vis.dtype
            )
            vis = torch.cat([vis, pad_vis], dim=0)
        vision_list.append(vis)

        # Original ids without visual placeholders
        orig_ids = b["input_ids"]
        orig_labels = b["labels"]
        text_ids = orig_ids[n_visual:]
        text_labels = orig_labels[n_visual:]

        # New placeholder + text
        new_placeholder_ids = torch.full((max_visual_tokens,), pad_id, dtype=torch.long)
        new_placeholder_labels = torch.full((max_visual_tokens,), -100, dtype=torch.long)

        new_ids = torch.cat([new_placeholder_ids, text_ids])
        new_labels = torch.cat([new_placeholder_labels, text_labels])

        # Right-pad text to match max total length
        total_len = max_visual_tokens + (max_text_len - n_visual)
        current_len = new_ids.size(0)
        pad_len = total_len - current_len

        if pad_len > 0:
            new_ids = torch.cat([new_ids, torch.full((pad_len,), pad_id, dtype=torch.long)])
            new_labels = torch.cat([new_labels, torch.full((pad_len,), -100, dtype=torch.long)])
        elif pad_len < 0:
            # Truncate (shouldn't happen, but safety)
            new_ids = new_ids[:total_len]
            new_labels = new_labels[:total_len]

        mask_len = max_visual_tokens + text_ids.size(0)
        total_final = new_ids.size(0)
        mask = torch.zeros(total_final, dtype=torch.long)
        mask[:mask_len] = 1

        input_ids_list.append(new_ids)
        labels_list.append(new_labels)
        attention_mask_list.append(mask)

    return {
        "vision": torch.stack(vision_list),
        "input_ids": torch.stack(input_ids_list),
        "attention_mask": torch.stack(attention_mask_list),
        "labels": torch.stack(labels_list),
        "n_visual_tokens": max_visual_tokens,
    }

collate_fn.pad_token_id = 0


